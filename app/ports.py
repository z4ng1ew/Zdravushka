# Порты (интерфейсы) внешних систем, от которых зависит логика ассистента.
# Диалог знает только этот контракт, а не конкретный класс: настоящий стенд (StandClient)
# и имитация (mock_stand) подставляются без изменения сценариев — принцип инверсии зависимостей.
from typing import Protocol


class SlotLock(Protocol):
    """Блокировка «проверить, что слот свободен → записать в МИС».

    Стенд «Регистратура» не проверяет занятость времени (условие кейса), поэтому атомарность
    обеспечивает ассистент. Реализация выбирается по схеме развёртывания:
      - один процесс (VM хакатона, uvicorn без воркеров) — asyncio.Lock (app/dialog/mis.py);
      - несколько инстансов — распределённая блокировка с тем же интерфейсом
        (например, Redis SET NX или advisory lock в БД регистратуры), сценарии не меняются."""

    async def __aenter__(self): ...
    async def __aexit__(self, *exc): ...


class MisPort(Protocol):
    """Что ассистенту нужно от МИС «Регистратура»."""

    async def active_doctors(self, specialty: str) -> list[dict]: ...
    async def find_client(self, last_name: str, first_name: str, birth_date: str) -> dict | None: ...
    async def create_client(self, last_name: str, first_name: str, birth_date: str,
                            middle_name: str | None = None, comment: str | None = None) -> dict: ...
    async def get_client(self, client_id: int) -> dict: ...
    async def update_client_comment(self, client_id: int, comment: str) -> dict: ...
    async def list_visits(self, client_id: int | None = None, doctor_id: int | None = None,
                          status: str | None = None, date_from: str | None = None,
                          date_to: str | None = None) -> list[dict]: ...
    async def create_visit(self, client_id: int, doctor_id: int, scheduled_at: str) -> dict: ...
    async def reschedule_visit(self, visit_id: int, scheduled_at: str) -> dict: ...
    async def cancel_visit(self, visit_id: int) -> dict: ...
    async def create_escalation(self, client_id: int, description: str) -> dict: ...
