# Просьба живого человека → R-02, немедленно, без уговоров
WANT_HUMAN = ["оператор", "живой человек", "живого человека", "с человеком", "сотрудник", "регистратор"]

# Жалоба → R-03, старший администратор
COMPLAINT = ["жалоб", "пожаловаться", "безобразие", "нагрубил", "хамств", "хамит", "буду жаловаться"]

# Острая зубная боль → R-09, стоматологическое отделение
DENTAL = ["болит зуб", "зубная боль", "флюс", "выбил зуб", "сломал зуб"]


def check(text: str) -> Escalation | None:
    """Возвращает карточку перевода, если фраза требует человека. Иначе None."""
    low = " " + text.lower().replace("ё", "е") + " "
    # Внезапная сильнейшая головная боль — возможный инсульт, это категория А
    if SUDDEN_HEADACHE.search(low):
        return Escalation(rule="R-01", reason="неотложное состояние", priority="P1", emergency=True,
                          summary=f"Внезапная сильная головная боль: «{text}»")
    norm = [w.replace("ё", "е") for w in RED_FLAGS_A]
    if any(w in low for w in norm):
        return Escalation(rule="R-01", reason="неотложное состояние", priority="P1", emergency=True,
                          summary=f"Красный флаг: «{text}»")
    if any(w.replace("ё", "е") in low for w in RED_FLAGS_B) or SEVERE_PAIN.search(low):
        return Escalation(rule="R-11", reason="острая боль", priority="P1",
                          summary=f"Острое состояние: «{text}»")
    if any(w in low for w in WANT_HUMAN):
        return Escalation(rule="R-02", reason="просьба оператора", priority="P2",
                          summary="Пациент попросил соединить с сотрудником")
    if any(w in low for w in COMPLAINT):
        return Escalation(rule="R-03", reason="жалоба", priority="P2", summary=f"Жалоба: «{text}»")
    if any(w in low for w in DENTAL):
        return Escalation(rule="R-09", reason="острая боль", priority="P2",
                          summary=f"Острая зубная боль: «{text}» — в стоматологию (доб. 2)")
    return None


